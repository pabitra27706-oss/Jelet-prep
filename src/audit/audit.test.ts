import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  auditCorpus,
  eligibilityMatrix,
  renderMarkdown,
  auditPaper,
  type CorpusAudit,
} from "../../scripts/content-audit.mjs";
import { papers, parsePaper, missingNumbers } from "../content";
import { contentSources, coveredYears } from "./sources";

const root = resolve(__dirname, "../..");
const corpus = import.meta.glob("../../pyq-md/*.md", {
  query: "?raw",
  import: "default",
  eager: true,
}) as Record<string, string>;

const audit: CorpusAudit = auditCorpus({
  papers: Object.fromEntries(
    Object.entries(corpus).map(([file, raw]) => [
      Number(file.replace("../../pyq-md/", "").replace(".md", "")),
      raw,
    ]),
  ),
  syllabus: readFileSync(resolve(root, "syllabus.md"), "utf8"),
  legacyHtml: readFileSync(resolve(root, "pyq-index.html"), "utf8"),
});

describe("committed content inventory", () => {
  it("matches the corpus (regenerate with npm run audit:content)", () => {
    const committed = JSON.parse(
      readFileSync(resolve(root, "docs/audits/content-audit.json"), "utf8"),
    );
    // Timestamp-free comparison: the generated body must not drift.
    expect(committed.paperAudits).toEqual(audit.paperAudits);
    expect(committed.syllabus).toEqual(audit.syllabus);
    expect(committed.legacyReader).toEqual(audit.legacyReader);
    expect(committed.totals).toEqual(audit.totals);
  });

  it("keeps the rendered Markdown inventory in step with the data", () => {
    const committed = readFileSync(
      resolve(root, "docs/audits/content-audit.md"),
      "utf8",
    );
    const regenerated = renderMarkdown(audit).replace(
      /^Generated by `npm run audit:content` on .*$/m,
      "",
    );
    expect(
      committed.replace(/^Generated by `npm run audit:content` on .*$/m, ""),
    ).toBe(regenerated);
  });
});

describe("audit integrity", () => {
  it("agrees with the runtime parser used by the website", () => {
    for (const paper of audit.paperAudits) {
      const raw = corpus[`../../pyq-md/${paper.year}.md`];
      const runtime = parsePaper(raw);
      expect(runtime.questions.map((q) => q.number)).toEqual(
        paper.questions.map((q) => q.number),
      );
      expect(missingNumbers(runtime.questions)).toEqual(paper.missing);
    }
  });

  it("covers every paper shipped in the library, and only those", () => {
    expect(audit.paperAudits.map((paper) => paper.year)).toEqual(
      papers.map((paper) => paper.year).sort((a, b) => a - b),
    );
    expect(audit.paperAudits.map((paper) => paper.year)).toEqual(coveredYears);
  });

  it("records the known gaps and the 2019 title conflict", () => {
    const byYear = new Map(
      audit.paperAudits.map((paper) => [paper.year, paper]),
    );
    expect(byYear.get(2019)!.missing).toEqual([78, 79]);
    expect(byYear.get(2022)!.missing).toEqual([86, 87, 88, 89, 90]);
    expect(byYear.get(2024)!.missing).toEqual([60, 61, 62]);
    expect(byYear.get(2019)!.titleMatchesFileName).toBe(false);
    expect(byYear.get(2019)!.title).toContain("2018");
    expect(
      audit.paperAudits.filter((paper) => paper.titleMatchesFileName === false),
    ).toHaveLength(1);
  });

  it("reports no duplicate numbers or unbalanced maths delimiters", () => {
    expect(audit.totals.duplicates).toBe(0);
    expect(audit.totals.unbalancedMath).toBe(0);
  });

  it("keeps every paper ineligible for scoring", () => {
    for (const row of eligibilityMatrix(audit)) {
      expect(row.readable).toBe(true);
      expect(row.transcriptionVerified).toBe(false);
      expect(row.keyVerified).toBe(false);
      expect(row.fullMockEligible).toBe(false);
    }
  });

  it("detects a regression in the audit itself", () => {
    const raw =
      "[intro]\n## MATHEMATICS (Q1–2)\n\n**1.** First $x$\n(A) a\n(B) b\n(C) c\n(D) d\n\n**2.** Duplicate of one\n(A) a\n";
    const single = auditPaper(raw, 2017);
    expect(single.questions).toHaveLength(2);
    expect(single.missing.length).toBe(98);
    expect(single.stats.fewerThanFourOptions).toBe(1);
    // Deliberately duplicated numbering must be reported, not silently merged.
    const duplicated = auditPaper("[i]\n## S (Q1)\n**1.** a\n**1.** b\n", 2017);
    expect(duplicated.duplicates).toHaveLength(1);
  });
});

describe("source register", () => {
  it("documents a retrieval status for every shipped paper", () => {
    for (const year of coveredYears) {
      const source = contentSources.find((entry) => entry.year === year)!;
      expect(source.url, `${year} URL`).toMatch(/^https:\/\//);
      expect(source.registryRetrievedAt, `${year} registry date`).toBeTruthy();
      expect(["official-listing", "official-pdf", "unverified"]).toContain(
        source.listingStatus,
      );
      expect(source.notes.length, `${year} carries a note`).toBeGreaterThan(0);
    }
  });

  it("does not claim verification that has not happened", () => {
    for (const source of contentSources) {
      if (source.transcriptionReview === "complete")
        throw new Error(`${source.year}: complete review is not established`);
      expect(source.listingStatus).not.toBe("official-pdf");
    }
    expect(
      contentSources.find((entry) => entry.year === 2022)?.transcriptionReview,
    ).toBe("sampled");
    expect(
      contentSources.filter(
        (entry) => entry.transcriptionReview === "not-compared",
      ),
    ).toHaveLength(6);
  });

  it("matches the paper years used by the library", () => {
    expect(
      contentSources.map((entry) => entry.year).sort((a, b) => a - b),
    ).toEqual(papers.map((paper) => paper.year).sort((a, b) => a - b));
  });
});
